def _absolute_to_raw(env, absolute: np.ndarray) -> torch.Tensor:
    term = env.action_manager.get_term("JointPositionAction")
    value = torch.as_tensor(absolute, dtype=torch.float32, device=env.device)
    return (value - term._offset) / term._scale


def _apply_approach_task_targets(env, high_level_action: np.ndarray) -> np.ndarray:
    """Route public navigation targets and hold the arms during far search."""
    result = np.asarray(high_level_action, dtype=np.float32).copy()
    command_term = env.command_manager.get_term("base_velocity")
    result[16:19] = command_term.command[0].detach().cpu().numpy()
    result[19] = 0.75
    result[20:23] = 0.0
    visible = bool(command_term.box_visible[0])
    if not visible:
        result[21] = args_cli.approach_search_torso_pitch_rad
    pregrasp_error_m = float(
        torch.linalg.vector_norm(command_term.pregrasp_position_error_b[0])
    )
    if visible and pregrasp_error_m <= 0.35:
        return result

    robot = env.scene["robot"]
    pelvis_id = body_id(robot, "pelvis")
    pelvis_position = robot.data.body_link_pos_w[0, pelvis_id]
    pelvis_quaternion = robot.data.body_link_quat_w[0, pelvis_id]
    pelvis_inverse = math_utils.quat_inv(pelvis_quaternion.unsqueeze(0))[0]
    for body_name, position_slice, quaternion_slice in (
        ("left_wrist_yaw_link", slice(2, 5), slice(5, 9)),
        ("right_wrist_yaw_link", slice(9, 12), slice(12, 16)),
    ):
        wrist_id = body_id(robot, body_name)
        wrist_position = robot.data.body_link_pos_w[0, wrist_id]
        wrist_quaternion = robot.data.body_link_quat_w[0, wrist_id]
        relative_position = math_utils.quat_apply(
            pelvis_inverse.unsqueeze(0),
            (wrist_position - pelvis_position).unsqueeze(0),
        )[0]
        relative_quaternion = math_utils.quat_mul(
            pelvis_inverse.unsqueeze(0), wrist_quaternion.unsqueeze(0)
        )[0]
        result[position_slice] = relative_position.detach().cpu().numpy()
        wxyz = relative_quaternion.detach().cpu().numpy()
        result[quaternion_slice] = wxyz[[1, 2, 3, 0]]
    result[:2] = 1.0
    return result


def _processed_student_action(env, policy, observation, student_bridge):
    prediction = np.asarray(policy(observation)[0], dtype=np.float32).copy()
    if policy.action_key == "processed_43d_joint_target":
        absolute = prediction.astype(np.float32, copy=False)
        return _absolute_to_raw(env, absolute[None]), absolute
    prediction = _apply_approach_task_targets(env, prediction)
    names, values = student_bridge.step(bridge_request(env, prediction))
    raw, absolute = action_order_target(env, names, values)
    return raw, absolute[0].detach().cpu().numpy()


def _smoothstep_handoff(target, reference, step: int, duration_steps: int):
    if reference is None or duration_steps <= 0 or step >= duration_steps:
        return target
    fraction = float(np.clip((step + 1) / duration_steps, 0.0, 1.0))
    blend = fraction * fraction * (3.0 - 2.0 * fraction)
    return reference + blend * (target - reference)


def _preserve_live_approach_legs(target, live_wbc, ordered_joint_names):
    leg_indices = tuple(
        index
        for index, name in enumerate(ordered_joint_names)
        if any(token in name for token in ("_hip_", "_knee_", "_ankle_"))
    )
    if len(leg_indices) != 12:
        raise RuntimeError(
            f"expected 12 leg joints for live grasp stance, got {len(leg_indices)}"
        )
    result = target.clone()
    result[:, leg_indices] = live_wbc[:, leg_indices]
    return result


def _correction_state(
    env, *, reference_box_quaternion_wxyz, qr_visible: bool, qr_was_visible: bool
):
    robot = env.scene["robot"]
    box = env.scene["box"]
    left_wrist = body_id(robot, "left_wrist_yaw_link")
    right_wrist = body_id(robot, "right_wrist_yaw_link")
    left_contact, right_contact = box_contact_counts(env)
    mean_wrist_velocity = 0.5 * (
        robot.data.body_link_lin_vel_w[0, left_wrist]
        + robot.data.body_link_lin_vel_w[0, right_wrist]
    )
    relative_speed = torch.linalg.vector_norm(
        box.data.root_link_lin_vel_w[0] - mean_wrist_velocity
    )
    return CorrectiveState(
        left_contact=left_contact > 0,
        right_contact=right_contact > 0,
        left_wrist_position_w=robot.data.body_link_pos_w[0, left_wrist]
        .detach()
        .cpu()
        .numpy(),
        right_wrist_position_w=robot.data.body_link_pos_w[0, right_wrist]
        .detach()
        .cpu()
        .numpy(),
        box_position_w=box.data.root_link_pos_w[0].detach().cpu().numpy(),
        box_quaternion_wxyz=box.data.root_link_quat_w[0].detach().cpu().numpy(),
        reference_box_quaternion_wxyz=reference_box_quaternion_wxyz,
        box_wrist_relative_speed_mps=float(relative_speed),
        lift_height_m=float(box.data.root_link_pos_w[0, 2])
        - (TABLE_SURFACE_HEIGHT_M + 0.5 * BOX_SIZE_M),
        qr_visible=qr_visible,
        qr_was_visible=qr_was_visible,
    )


def _flag_names(flags: CorrectionType) -> list[str]:
    return [
        item.name.lower()
        for item in CorrectionType
        if item != CorrectionType.NONE and flags & item
    ]


